import { z } from "zod";
import { confirmSubscriptionEmail } from "@/lib/email/templates";
import type { Mailer } from "@/lib/sources";

export const subscribeInputSchema = z.object({
  email: z.string().trim().toLowerCase().email().max(254),
  /** Honeypot: real people never see or fill this field. */
  website: z.string().max(0).optional(),
});

export const CONFIRMATION_COOLDOWN_MS = 10 * 60_000;

export interface SubscriberRow {
  email: string;
  confirm_token: string;
  confirmed_at: string | null;
  confirmation_sent_at: string | null;
}

export interface SubscribeStore {
  get(email: string): Promise<SubscriberRow | null>;
  /** Insert a new unconfirmed subscriber (token generated by the database) and return it. */
  create(email: string, source: string): Promise<SubscriberRow>;
  markConfirmationSent(email: string, at: Date): Promise<void>;
  confirmByToken(token: string, at: Date): Promise<boolean>;
}

export type SubscribeOutcome = "sent" | "already_confirmed" | "cooldown" | "ignored";

/**
 * Start a double opt-in subscription. The HTTP layer always answers the same "check your email" message
 * regardless of the outcome, so the form cannot be used to discover who is subscribed.
 */
export async function startSubscription(
  input: unknown,
  deps: { store: SubscribeStore; mailer: Mailer; appUrl: string; now?: Date; source?: string },
): Promise<SubscribeOutcome> {
  const parsed = subscribeInputSchema.safeParse(input);
  if (!parsed.success) return "ignored"; // includes a filled honeypot
  const now = deps.now ?? new Date();
  const { email } = parsed.data;

  let row = await deps.store.get(email);
  if (row?.confirmed_at) return "already_confirmed";
  if (
    row?.confirmation_sent_at &&
    now.getTime() - new Date(row.confirmation_sent_at).getTime() < CONFIRMATION_COOLDOWN_MS
  ) {
    return "cooldown"; // never let the form be used to flood someone's inbox
  }
  row ??= await deps.store.create(email, deps.source ?? "web");

  const confirmUrl = `${deps.appUrl.replace(/\/+$/, "")}/subscribe/confirm?t=${row.confirm_token}`;
  const msg = confirmSubscriptionEmail({ confirmUrl });
  await deps.mailer.send({ to: email, subject: msg.subject, html: msg.html, text: msg.text });
  await deps.store.markConfirmationSent(email, now);
  return "sent";
}

export const confirmTokenSchema = z.string().regex(/^[0-9a-f]{32}$/);

/** Confirm by token. Idempotent from the user's view; false for unknown/malformed tokens. */
export async function confirmSubscription(
  token: unknown,
  deps: { store: SubscribeStore; now?: Date },
): Promise<boolean> {
  const parsed = confirmTokenSchema.safeParse(token);
  if (!parsed.success) return false;
  return deps.store.confirmByToken(parsed.data, deps.now ?? new Date());
}
