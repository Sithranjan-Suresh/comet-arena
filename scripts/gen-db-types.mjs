#!/usr/bin/env node
// Generates lib/supabase/database.types.ts from the migrated local test database
// (same shape as `supabase gen types typescript`, which needs Docker).
//   npm run db:test   # (or: scripts/db-test.sh reset)  to build the DB
//   npm run db:types
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const PORT = process.env.PGPORT ?? "54329";
const asRoot = process.getuid?.() === 0;
function q(sql) {
  const args = ["-p", PORT, "-h", "/tmp", "-d", "comet", "-At", "-X", "-c", sql];
  const bin = "/usr/lib/postgresql/16/bin/psql";
  const out = asRoot
    ? execFileSync("su", [
        "postgres",
        "-c",
        [bin, ...args].map((a) => `'${a.replace(/'/g, "'\\''")}'`).join(" "),
      ])
    : execFileSync(bin, args);
  return JSON.parse(out.toString().trim() || "null");
}

const cols = q(`select json_agg(t) from (
  select c.table_name, c.column_name, c.udt_name, c.data_type, c.is_nullable = 'YES' as nullable,
         c.column_default is not null as has_default, c.is_generated = 'ALWAYS' as generated,
         t.table_type = 'VIEW' as is_view, c.ordinal_position
  from information_schema.columns c
  join information_schema.tables t using (table_schema, table_name)
  where c.table_schema = 'public' order by c.table_name, c.ordinal_position) t`);
const enums = q(`select json_object_agg(t.typname, t.vals) from (
  select t.typname, json_agg(e.enumlabel order by e.enumsortorder) as vals
  from pg_type t join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' group by t.typname) t`);
const funcs = q(`select coalesce(json_agg(p.proname order by p.proname), '[]') from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.prokind = 'f'
  and p.prorettype <> 'trigger'::regtype`);

const scalar = {
  uuid: "string",
  text: "string",
  varchar: "string",
  bpchar: "string",
  timestamptz: "string",
  timestamp: "string",
  date: "string",
  bool: "boolean",
  int2: "number",
  int4: "number",
  int8: "number",
  float4: "number",
  float8: "number",
  numeric: "number",
  jsonb: "Json",
  json: "Json",
  vector: "string",
  tsvector: "string",
};
function tsType(c) {
  const isArr = c.data_type === "ARRAY";
  const base = isArr ? c.udt_name.replace(/^_/, "") : c.udt_name;
  const t = enums[base] ? `Database["public"]["Enums"]["${base}"]` : (scalar[base] ?? "unknown");
  return isArr ? `${t}[]` : t;
}

const tables = {};
for (const c of cols) (tables[c.table_name] ??= { view: c.is_view, cols: [] }).cols.push(c);

let out = `// GENERATED by scripts/gen-db-types.mjs. Do not edit by hand. Run \`npm run db:types\`.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [name, t] of Object.entries(tables).filter(([, t]) => !t.view)) {
  const row = t.cols
    .map((c) => `          ${c.column_name}: ${tsType(c)}${c.nullable ? " | null" : ""}`)
    .join("\n");
  const ins = t.cols
    .filter((c) => !c.generated)
    .map((c) => {
      const opt = c.nullable || c.has_default ? "?" : "";
      return `          ${c.column_name}${opt}: ${tsType(c)}${c.nullable ? " | null" : ""}`;
    })
    .join("\n");
  const upd = t.cols
    .filter((c) => !c.generated)
    .map((c) => `          ${c.column_name}?: ${tsType(c)}${c.nullable ? " | null" : ""}`)
    .join("\n");
  out += `      ${name}: {\n        Row: {\n${row}\n        }\n        Insert: {\n${ins}\n        }\n        Update: {\n${upd}\n        }\n        Relationships: []\n      }\n`;
}
out += `    }\n    Views: {\n`;
for (const [name, t] of Object.entries(tables).filter(([, t]) => t.view)) {
  const row = t.cols.map((c) => `          ${c.column_name}: ${tsType(c)} | null`).join("\n");
  out += `      ${name}: {\n        Row: {\n${row}\n        }\n        Relationships: []\n      }\n`;
}
out += `    }\n    Functions: {\n`;
for (const f of funcs) out += `      ${f}: { Args: Record<string, unknown>; Returns: unknown }\n`;
out += `    }\n    Enums: {\n`;
for (const [n, v] of Object.entries(enums))
  out += `      ${n}: ${v.map((x) => JSON.stringify(x)).join(" | ")}\n`;
out += `    }\n    CompositeTypes: { [_ in never]: never }\n  }\n}\n`;
writeFileSync(new URL("../lib/supabase/database.types.ts", import.meta.url), out);
console.log(`wrote lib/supabase/database.types.ts (${Object.keys(tables).length} relations)`);
